import type { RowResult } from './harness.ts';
import type { HttpSimRow } from './http-sim.ts';
import { NETWORKS } from './http-sim.ts';
import { formatBytes, formatMs, formatRatio } from './stats.ts';
import type { Corpus } from './corpora.ts';

export type ReportMeta = {
  generatedAt: string;
  nodeVersion: string;
  platform: string;
  arch: string;
  notes: string[];
  warmup: number;
  iterations: number;
};

const mdEscape = (s: string): string => s.replace(/\|/g, '\\|');

export const buildMarkdownReport = (
  meta: ReportMeta,
  corpora: Corpus[],
  rows: RowResult[],
  http: HttpSimRow[]
): string => {
  const lines: string[] = [];
  lines.push('# Phase 0 — Baseline benchmark report');
  lines.push('');
  lines.push('> Auto-generated by `npm run bench`. Re-run after every phase and record the delta.');
  lines.push('');
  lines.push('## Environment');
  lines.push('');
  lines.push(`| | |`);
  lines.push(`|---|---|`);
  lines.push(`| Generated | ${meta.generatedAt} |`);
  lines.push(`| Node | ${meta.nodeVersion} |`);
  lines.push(`| Platform | ${meta.platform}/${meta.arch} |`);
  lines.push(`| Warmup / iterations | ${meta.warmup} / ${meta.iterations} (scaled down for large payloads) |`);
  lines.push(`| Outliers | IQR fence trim when N≥8, keep ≥75% samples |`);
  if (meta.notes.length) {
    lines.push(`| Notes | ${meta.notes.map(mdEscape).join('; ')} |`);
  }
  lines.push('');

  lines.push('## Corpora');
  lines.push('');
  lines.push('| ID | Name | Bytes | Description |');
  lines.push('|----|------|------:|-------------|');
  for (const c of corpora) {
    lines.push(
      `| ${c.id} | ${c.name} | ${c.bytes.length} (${formatBytes(c.bytes.length)}) | ${mdEscape(c.description)} |`
    );
  }
  lines.push('');

  lines.push('## Compression matrix');
  lines.push('');
  lines.push(
    '| Corpus | Codec | Original | Compressed | Ratio | Enc p50 | Enc p95 | Enc p99 | Dec p50 | Dec p99 | RSS Δ |'
  );
  lines.push(
    '|--------|-------|--------:|-----------:|------:|--------:|--------:|--------:|--------:|--------:|------:|'
  );

  const sorted = [...rows].sort((a, b) =>
    a.corpusId === b.corpusId
      ? a.codecId.localeCompare(b.codecId)
      : a.corpusId.localeCompare(b.corpusId)
  );

  for (const r of sorted) {
    if (r.error) {
      lines.push(
        `| ${r.corpusId} | ${r.codecName} | ${r.originalBytes} | — | — | — | — | — | — | — | error: ${mdEscape(r.error)} |`
      );
      continue;
    }
    lines.push(
      `| ${r.corpusId} | ${r.codecName} | ${formatBytes(r.originalBytes)} | ${formatBytes(r.compressedBytes)} | ${formatRatio(r.compressedBytes, r.originalBytes)} | ${formatMs(r.encode.p50)} | ${formatMs(r.encode.p95)} | ${formatMs(r.encode.p99)} | ${formatMs(r.decode.p50)} | ${formatMs(r.decode.p99)} | ${formatBytes(r.rssDeltaBytes)} |`
    );
  }
  lines.push('');

  lines.push('## Encode latency vs zstd L3 (same corpus)');
  lines.push('');
  lines.push('Positive = slower than zstd L3. This is the honesty check for OpenZL serial today.');
  lines.push('');
  lines.push('| Corpus | openzl serial enc p50 | zstd L3 enc p50 | Δ | ratio openzl | ratio zstd L3 |');
  lines.push('|--------|----------------------:|----------------:|--:|-------------:|--------------:|');

  const byKey = new Map(rows.filter((r) => !r.error).map((r) => [`${r.corpusId}::${r.codecId}`, r]));
  const corpusIds = [...new Set(rows.map((r) => r.corpusId))];
  for (const id of corpusIds) {
    const oz = byKey.get(`${id}::openzl-serial`);
    const zs = byKey.get(`${id}::zstd-3`);
    if (!oz || !zs) continue;
    const delta = oz.encode.p50 - zs.encode.p50;
    const sign = delta >= 0 ? '+' : '';
    lines.push(
      `| ${id} | ${formatMs(oz.encode.p50)} | ${formatMs(zs.encode.p50)} | ${sign}${formatMs(delta)} | ${formatRatio(oz.compressedBytes, oz.originalBytes)} | ${formatRatio(zs.compressedBytes, zs.originalBytes)} |`
    );
  }
  lines.push('');

  lines.push('## Size sweep crossover (corpus E, encode p50)');
  lines.push('');
  lines.push('When encode cost exceeds transfer savings, compression loses. Chart is log-ish ASCII of encode p50.');
  lines.push('');

  const eRows = rows.filter((r) => r.corpusId.startsWith('E-') && !r.error);
  const eCodecs = [...new Set(eRows.map((r) => r.codecId))];
  const eSizes = [...new Set(eRows.map((r) => r.corpusId))];

  // Table of encode p50 by size × codec
  lines.push('| Size | ' + eCodecs.map((c) => c).join(' | ') + ' |');
  lines.push('|------|' + eCodecs.map(() => '------:').join('|') + '|');
  for (const size of eSizes) {
    const cells = eCodecs.map((cid) => {
      const row = eRows.find((r) => r.corpusId === size && r.codecId === cid);
      return row ? formatMs(row.encode.p50) : '—';
    });
    lines.push(`| ${size} | ${cells.join(' | ')} |`);
  }
  lines.push('');

  // ASCII chart for openzl vs zstd-3 vs gzip-6 encode p50
  const chartCodecs = ['openzl-serial', 'zstd-3', 'gzip-6'].filter((c) =>
    eRows.some((r) => r.codecId === c)
  );
  if (chartCodecs.length && eSizes.length) {
    lines.push('### Encode p50 (relative bar, per size)');
    lines.push('');
    lines.push('```');
    for (const size of eSizes) {
      const vals = chartCodecs.map((cid) => {
        const row = eRows.find((r) => r.corpusId === size && r.codecId === cid);
        return { cid, ms: row?.encode.p50 ?? 0 };
      });
      const max = Math.max(...vals.map((v) => v.ms), 0.001);
      lines.push(size);
      for (const v of vals) {
        const width = Math.max(1, Math.round((v.ms / max) * 40));
        lines.push(`  ${v.cid.padEnd(14)} ${'█'.repeat(width)} ${formatMs(v.ms)}`);
      }
    }
    lines.push('```');
    lines.push('');
  }

  lines.push('## HTTP simulation (encode p50 + network)');
  lines.push('');
  lines.push(
    'Model: `TTFB = encode_p50 + RTT/2`, `total = encode_p50 + RTT + transfer(compressed)`. Identity has no encode cost.'
  );
  lines.push('');
  for (const net of NETWORKS) {
    lines.push(`### ${net.name}`);
    lines.push('');
    lines.push(
      '| Corpus | Codec | Compressed | Enc p50 | Transfer | TTFB | Total | vs identity |'
    );
    lines.push(
      '|--------|-------|-----------:|--------:|---------:|-----:|------:|------------:|'
    );
    const subset = http
      .filter((h) => h.networkId === net.id)
      .sort((a, b) =>
        a.corpusId === b.corpusId
          ? a.codecId.localeCompare(b.codecId)
          : a.corpusId.localeCompare(b.corpusId)
      );
    // Keep report readable: show 100kb-class corpora + size sweep extremes
    const filtered = subset.filter(
      (h) =>
        !h.corpusId.startsWith('E-') ||
        h.corpusId === 'E-1kb' ||
        h.corpusId === 'E-100kb' ||
        h.corpusId === 'E-1mb' ||
        h.corpusId === 'E-10mb'
    );
    for (const h of filtered) {
      const saved = h.savedMs;
      const savedStr = `${saved >= 0 ? '+' : ''}${formatMs(saved)} saved`;
      lines.push(
        `| ${h.corpusId} | ${h.codecId} | ${formatBytes(h.compressedBytes)} | ${formatMs(h.encodeP50Ms)} | ${formatMs(h.transferMs)} | ${formatMs(h.ttfbMs)} | ${formatMs(h.totalMs)} | ${savedStr} |`
      );
    }
    lines.push('');
  }

  lines.push('## Reading the baseline');
  lines.push('');
  lines.push(
    '- **openzl serial** uses the in-process N-API addon when available (Phase 2), else CLI pipes (Phase 1).'
  );
  lines.push(
    '- Ratio without a named corpus is meaningless — compare within a corpus row, not across A vs C.'
  );
  lines.push(
    '- zstd L3 is the honest bar. Ratio wins for typed/numeric data are Phase 3 (trained profiles).'
  );
  lines.push(
    '- Set `OPENZL_NATIVE=0` to force the CLI path when comparing backends.'
  );
  lines.push('');

  return lines.join('\n');
};

export const rowsToJson = (
  meta: ReportMeta,
  corpora: Corpus[],
  rows: RowResult[],
  http: HttpSimRow[]
): string =>
  JSON.stringify(
    {
      meta,
      corpora: corpora.map((c) => ({
        id: c.id,
        name: c.name,
        description: c.description,
        bytes: c.bytes.length
      })),
      rows,
      http
    },
    null,
    2
  );
